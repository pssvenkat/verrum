import Link from "next/link";
import { PageShell } from "@/components/layout/app-shell";
import { Badge } from "@/components/ui/badge";
import { DataTable, Td, Th } from "@/components/ui/data-table";
import { decisions, getDecisionMachine } from "@/domain/demo/seed";
import { formatCurrency } from "@/lib/utils";

export default function DecisionsPage() {
  return (
    <PageShell
      title="Decisions"
      description="Operational case files generated by deterministic rules and backed by evidence."
    >
      <DataTable>
        <thead>
          <tr>
            <Th>Decision</Th>
            <Th>Machine</Th>
            <Th>Priority</Th>
            <Th>Financial impact</Th>
            <Th>Evidence</Th>
            <Th>Status</Th>
          </tr>
        </thead>
        <tbody>
          {decisions.map((decision) => {
            const machine = getDecisionMachine(decision);
            return (
              <tr key={decision.id} className="hover:bg-surface-muted/60">
                <Td>
                  <Link href={`/decisions/${decision.id}`} className="font-medium text-primary hover:underline">
                    {decision.title}
                  </Link>
                  <div className="text-xs text-muted-foreground">{decision.recommendation}</div>
                </Td>
                <Td>{machine ? `${machine.make} ${machine.model} · Unit ${machine.unitNumber}` : "Unknown"}</Td>
                <Td>
                  <Badge tone={decision.priority === "high" ? "danger" : decision.priority === "medium" ? "warning" : "info"}>
                    {decision.priority}
                  </Badge>
                </Td>
                <Td className="font-semibold tabular">
                  {decision.financialImpact ? formatCurrency(decision.financialImpact) : "Not financial"}
                </Td>
                <Td>
                  <Badge tone={decision.evidenceState === "complete" ? "success" : "warning"}>
                    {decision.evidenceState}
                  </Badge>
                </Td>
                <Td>{decision.status}</Td>
              </tr>
            );
          })}
        </tbody>
      </DataTable>
    </PageShell>
  );
}
